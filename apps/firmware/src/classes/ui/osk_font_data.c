size_t osk_font_glyph_count(void)
{
	return (size_t)(FONT_ASCII_COUNT + FONT_EXTRA_COUNT);
}

/* Codepunkt -> Platz. Unbekanntes bekommt das Fragezeichen, nie eine Luecke. */
size_t osk_font_index(uint32_t codepoint)
{
	if (codepoint >= 0x20u && codepoint < 0x7Fu) {
		return (size_t)(codepoint - 0x20u);
	}
	for (size_t i = 0; i < FONT_EXTRA_COUNT; i++) {
		if (font_extra_cp[i] == codepoint) {
			return (size_t)FONT_ASCII_COUNT + i;
		}
	}
	return (size_t)(0x3Fu - 0x20u); /* ? */
}

/* Zeile einer Schriftstelle holen - die Tabellen liegen flach. */
uint8_t osk_font_row(const osk_font_t *font, size_t index, uint8_t row)
{
	if (font == NULL || row >= font->rows || index >= osk_font_glyph_count()) {
		return 0;
	}
	return font->glyphs[index * font->rows + row];
}
